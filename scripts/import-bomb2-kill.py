"""Import original kill-mode timelines from the retained FFDec sprite export."""
from pathlib import Path
from PIL import Image
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'artifacts/swf-analysis/9109/kill-preview'
OUT = ROOT / 'public/expanded/assets/bomb2'
symbols = {
    'hammer-down': 3631, 'hammer-left': 3636, 'hammer-right': 3639, 'hammer-up': 3654,
    'launcher-down': 3600, 'launcher-left': 3602, 'launcher-right': 3604, 'launcher-up': 3605,
    'shotgun-down': 3608, 'shotgun-left': 3611, 'shotgun-right': 3612, 'shotgun-up': 3614,
    'laser-ready': 3596, 'fire': 3661,
    'dead-0': 3020, 'dead-1': 3154, 'dead-2': 3248, 'dead-3': 3323,
}
metadata = {}
for name, symbol in symbols.items():
    folder = next(SOURCE.glob(f'DefineSprite_{symbol}*'))
    frames = [Image.open(p).convert('RGBA') for p in sorted(folder.glob('*.png'), key=lambda p: int(p.stem))]
    boxes = [frame.getbbox() for frame in frames if frame.getbbox()]
    box = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    w, h = box[2] - box[0], box[3] - box[1]
    strip = Image.new('RGBA', (w * len(frames), h))
    for n, frame in enumerate(frames):
        strip.alpha_composite(frame.crop(box), (n * w, 0))
    strip.save(OUT / f'kill-{name}.png')
    # Keep timeline registration stable instead of recentering each frame.
    # Runtime hand/feet placement remains a documented cosmetic adaptation.
    first = frames[0].getbbox()
    metadata[name] = {'frames': len(frames), 'w': w, 'h': h,
                      'x': box[0] - frames[0].width / 2,
                      'y': box[1] - frames[0].height / 2,
                      'feet': first[3] - box[1] if first else h,
                      'symbol': symbol}
(ROOT / 'src/expanded/bomb2-kill-art.ts').write_text(
    '// Original FFDec timelines, generated by scripts/import-bomb2-kill.py.\n'
    'export const KILL_ART:Record<string,{frames:number,w:number,h:number,x:number,y:number,feet:number,symbol:number}> = '
    + json.dumps(metadata, separators=(',', ':')) + ';\n', encoding='utf-8')
manifest_file = OUT / 'manifest.json'
manifest = json.loads(manifest_file.read_text(encoding='utf-8'))
manifest['killTimelines'] = metadata
manifest['assets'] = [{'path': p.relative_to(OUT).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                      for p in sorted(OUT.rglob('*')) if p.is_file() and p.name != 'manifest.json']
manifest_file.write_text(json.dumps(manifest, indent=2), encoding='utf-8')
print(f'Imported {len(metadata)} original kill-mode timelines; {len(manifest["assets"])} total Bomb2 assets')
