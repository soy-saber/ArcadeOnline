"""Reproducible local import from FFDec's 9109 embedded payload exports."""
from pathlib import Path
from PIL import Image
import csv, re, json, hashlib, shutil, sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'artifacts/swf-analysis/9109'
OUT = ROOT / 'public/expanded/assets/bomb2'
OUT.mkdir(parents=True, exist_ok=True)
themes = [('Mine',1),('Beach',11),('Snow',21),('Disce',31),('Factory',41),('Center',51)]
maps = []
for theme, begin in themes:
    path = SOURCE / f'embedded/scripts/actionSprite/mapData/{theme}MapData.as'
    read_path = path
    if '--maps-only' in sys.argv and not read_path.exists():
        read_path = ROOT / 'artifacts/swf-analysis/9109-restore/embedded/scripts/actionSprite/mapData' / path.name
    source = read_path.read_text(encoding='utf-8-sig')
    methods = re.findall(r'private function (set\w+)\(\) : void\s*\{(.*?)(?=\n      \}|\Z)', source, re.S)
    for method, body in methods:
        ops = []
        for name,args in re.findall(r'_mapMaster\.(set\w+)\(([^)]*)\)', body):
            if name not in ['setFixedProb','setUnfixedProb','setNull','setMidBox','setResistance','setOtherProb']: continue
            vals = [True if x.strip()=='true' else False if x.strip()=='false' else float(x.strip()) for x in args.split(',')]
            ops.append([name,*vals])
        hazards=[]
        pairs={}
        for line in body.splitlines():
            match=re.search(r'(?:(\w+) = )?new (QuickSand|Transmittal|SpringBoard|IceFace|Rail|TurnTable)\(_game,([^)]*)\)',line)
            if match:
                variable, kind, args=match.groups(); values=[int(x.strip()) for x in args.split(',')]
                if variable: pairs[variable]=len(hazards)
                hazards.append({'kind':kind,'x':values[0],'y':values[1],'dir':values[2] if len(values)>2 else 0})
            match=re.search(r'(\w+)\.aimSand = (\w+)',line)
            if match and all(v in pairs for v in match.groups()): hazards[pairs[match[1]]]['target']=pairs[match[2]]
            match=re.search(r'(\w+)\.addTurn\((\d+)\)',line)
            if match and match[1] in pairs:
                hazard=hazards[pairs[match[1]]]
                hazard.setdefault('turns',[hazard['dir']]).append(int(match[2]))
        layout=re.search(r'(One|Two|Three)$',method)[1].lower()
        maps.append({'id':theme.lower()+'-'+layout,'theme':theme.lower(),'begin':begin,'source':str(path.relative_to(ROOT)).replace('\\','/'),'method':method,'ops':ops,'hazards':hazards})
(ROOT/'src/expanded/bomb2-maps.ts').write_text('// Generated by scripts/import-expanded-bomb2.py from all 18 authored AS methods.\nexport const MAPS = '+json.dumps(maps,separators=(',',':'))+' as const;\n',encoding='utf-8')
if '--maps-only' in sys.argv:
    print(f'Imported {len(maps)} maps; {sum("turns" in h for m in maps for h in m["hazards"])} rotating conveyors')
    sys.exit(0)

symbols={name:int(char) for char,name in csv.reader((SOURCE/'embedded/symbolClass/symbols.csv').open(encoding='utf-8'),delimiter=';')}
preview=SOURCE/'runtime-preview'
def directory(symbol): return next(preview.glob('DefineSprite_'+str(symbols[symbol])+'_*'))
def crop(file):
    image=Image.open(file).convert('RGBA'); bounds=image.getbbox()
    return image.crop(bounds) if bounds else image
for theme,_ in themes:
    crop(directory('BackGround_'+theme)/'1.png').save(OUT/('background-'+theme.lower()+'.png'))
brick=directory('brick')
brick_meta={}
for file in brick.glob('*.png'):
    raw=Image.open(file).convert('RGBA');box=raw.getbbox()
    crop(file).save(OUT/('brick-'+file.name))
    # Shared FFDec raster canvas; frame 1 PlaceObject has x=0,y=-15.
    brick_meta[file.stem]={'x':box[0]-70,'y':box[1]-56,'w':box[2]-box[0],'h':box[3]-box[1]} if box else {'x':0,'y':0,'w':0,'h':0}
(ROOT/'src/expanded/bomb2-art.ts').write_text('// Authored registration offsets in 30px cells, derived from FFDec canvas and placement.\nexport const BRICKS:Record<number,{x:number,y:number,w:number,h:number}> = '+json.dumps(brick_meta,separators=(',',':'))+';\n',encoding='utf-8')
for hero in range(4):
    for direction in ['Left','Up','Right','Down']:
        folder=directory(f'_r{hero}_{direction}')
        frames=[Image.open(p).convert('RGBA') for p in sorted(folder.glob('*.png'),key=lambda p:int(p.stem))]
        boxes=[f.getbbox() for f in frames if f.getbbox()]
        box=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
        width,height=box[2]-box[0],box[3]-box[1]
        strip=Image.new('RGBA',(width*len(frames),height))
        for i,frame in enumerate(frames):strip.alpha_composite(frame.crop(box),(i*width,0))
        strip.save(OUT/f'hero-{hero}-{direction.lower()}.png')
        (OUT/f'hero-{hero}-{direction.lower()}.json').write_text(json.dumps({'frames':len(frames),'width':width,'height':height}))
for symbol,name in [('bomb0','bomb'),('exp0','blast'),('prop','prop')]:
    folder=directory(symbol)
    for file in folder.glob('*.png'):crop(file).save(OUT/(name+'-'+file.name))
for symbol,name in [('quickSand_1','quicksand-1'),('quickSand_2','quicksand-2'),('turnTable','turntable'),('tramcar','tramcar'),('transmittal','conveyor'),('rail','rail')]:
    for file in directory(symbol).glob('*.png'):crop(file).save(OUT/(name+'-'+file.name))
for hero in range(4):
    for kind in ['Car','Bulldozer','Frog']:
        for direction in ['Left','Up','Right','Down']:
            try:folder=directory(f'_r{hero}_{kind}_{direction}')
            except StopIteration:continue
            crop(folder/'1.png').save(OUT/f'vehicle-{hero}-{kind.lower()}-{direction.lower()}.png')
for name in ['images','shapes','morphshapes','sounds','texts','symbolClass']:
    shutil.copytree(SOURCE/'embedded'/name,OUT/'original'/name,dirs_exist_ok=True)
identity={'raw':'games/9109/game.swf','rawSha256':hashlib.sha256((ROOT/'games/9109/game.swf').read_bytes()).hexdigest(),'embeddedSha256':hashlib.sha256((SOURCE/'embedded.swf').read_bytes()).hexdigest(),'maps':len(maps),'assets':[]}
for file in sorted(OUT.rglob('*')):
    if file.is_file() and file.name!='manifest.json':identity['assets'].append({'path':str(file.relative_to(OUT)).replace('\\','/'),'sha256':hashlib.sha256(file.read_bytes()).hexdigest()})
(OUT/'manifest.json').write_text(json.dumps(identity,indent=2),encoding='utf-8')
print(f'Imported {len(maps)} maps and {len(identity["assets"])} original/runtime assets')
